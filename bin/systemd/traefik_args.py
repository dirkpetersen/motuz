"""
Traefik's static configuration for the systemd install (bin/systemd/deploy.sh): the
`command` flags of the traefik service in docker-compose.yml, so both installs use the
same flags, with this install's paths and the MOTUZ_ACME_* settings of motuz.env.
Prints the line TRAEFIK_ARGS=<flags> for ~/.config/motuz/traefik.env
(motuz-traefik.service passes $TRAEFIK_ARGS, split at spaces, to traefik).

Usage: python3 traefik_args.py docker-compose.yml DYNAMIC_DIR ACME_JSON ACME_EMAIL ACME_CA_SERVER
Standard library only (it runs with Ubuntu's python3, before the venv exists).
"""
import re
import sys


def compose_flags(text):
    """The `- --flag` items of services.traefik.command in docker-compose.yml"""
    flags, in_traefik, in_command = [], False, False
    for line in text.splitlines():
        if re.match(r'^    \S', line): # a service
            in_traefik = line.strip() == 'traefik:'
            in_command = False
            continue
        if not in_traefik:
            continue
        if re.match(r'^        command:\s*$', line):
            in_command = True
            continue
        if in_command:
            match = re.match(r'^\s+- (--\S+)(\s+#.*)?$', line)
            if match:
                flags.append(match.group(1))
            elif line.strip() and not line.strip().startswith('#'):
                in_command = False
    return flags


def systemd_flags(flags, dynamic_dir, acme_json, settings):
    """Compose's ${NAME:-default} from `settings`, the container paths replaced"""
    def substitute(match):
        return settings.get(match.group(1)) or match.group(2) or ''

    out = []
    for flag in flags:
        flag = re.sub(r'\$\{(\w+)(?::-([^}]*))?\}', substitute, flag)
        flag = flag.replace('=/etc/traefik/dynamic', '=' + dynamic_dir)
        flag = flag.replace('=/etc/traefik/acme/acme.json', '=' + acme_json)
        if re.search(r'[\s"\'\\$]', flag) or '/etc/traefik' in flag:
            raise ValueError('unexpected Traefik flag ' + flag)
        out.append(flag)
    required = ('--entryPoints.web.address=:80', '--entryPoints.websecure.address=:443',
                '--providers.file.directory=' + dynamic_dir)
    if not all(r in out for r in required):
        raise ValueError('the traefik command in docker-compose.yml was not found')
    return out


def main(argv):
    compose, dynamic_dir, acme_json, email, ca_server = argv[1:6]
    with open(compose) as f:
        flags = systemd_flags(compose_flags(f.read()), dynamic_dir, acme_json,
                              {'MOTUZ_ACME_EMAIL': email, 'MOTUZ_ACME_CA_SERVER': ca_server})
    print('# Generated by bin/systemd/deploy.sh from docker-compose.yml (traefik command); do not edit')
    print('TRAEFIK_ARGS=' + ' '.join(flags))


if __name__ == '__main__':
    try:
        main(sys.argv)
    except (ValueError, OSError) as e:
        sys.exit('traefik_args.py: {}'.format(e))
